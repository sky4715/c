#include <stdio.h>

int main(void){
    int grade, n; // 성적을 저장할 변수와 학생 수를 셀 변수
    float sum, average; // 성적 합계와 평균을 저장할 변수

    // 필요한 변수들을 초기화한다
    n = 0; // 학생 수를 카운트할 변수 초기화
    sum = 0; // 성적 합계 초기화
    grade = 0; // 입력받을 성적 변수 초기화

    printf("성적 입력을 종료하려면 음수를 입력하시오\n");

    // 성적을 입력 받아서 합계를 구하고 학생 수를 센다
    while(grade >= 0){ // 음수를 입력받기 전까지 반복
        printf("성적을 입력하시오: ");
        scanf("%d", &grade); // 사용자로부터 성적을 입력받음

        if (grade >= 0) { // 음수가 아닌 경우만 합계에 더함
            sum += grade; // 입력받은 성적을 합계에 추가
            n++; // 학생 수 증가
        }
    }

    // 마지막 음수 입력을 제외하기 위해 수정
    // 합계에서 마지막 음수를 제거
    // 학생 수에서 마지막 음수 입력을 제외
    // (입력한 성적만 계산)
    if (n > 0) { // 학생이 1명 이상일 때만 계산
        // 평균을 계산하고 화면에 출력한다
        average = sum / n;
        printf("성적의 평균은 %f입니다.\n", average);
    } else {
        printf("입력된 성적이 없습니다.\n");
    }

    return 0; // 프로그램 정상 종료
}
