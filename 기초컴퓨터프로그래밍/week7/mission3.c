#include <stdio.h>

int main(void) {
    int count = 1; // 출력할 숫자를 위한 변수 초기화

    // 5행을 출력하기 위한 외부 반복문
    for (int y = 0; y < 5; y++) {
        // 각 행에 5개의 항목을 출력하기 위한 내부 반복문
        for (int x = 0; x < 5; x++) {
            // count가 3의 배수일 경우 "!!" 출력
            if (count % 3 == 0)
                printf("!!\t");
            else
                printf("%d\t", count); // 3의 배수가 아닐 경우 숫자 출력
            
            count++; // 다음 숫자를 위해 count 증가
        }
        printf("\n"); // 한 줄 출력 후 줄바꿈
    }

    return 0; // 프로그램 종료
}
