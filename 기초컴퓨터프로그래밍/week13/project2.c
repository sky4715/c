#include <stdio.h> // 표준 입출력 라이브러리 포함

int main(void) { // main 함수 시작
    int num[5] = {0}; // 크기가 5인 정수형 배열을 선언하고 모든 요소를 0으로 초기화
    int sum = 0, size; // 합계를 저장할 변수 sum과 배열 크기를 저장할 변수 size 선언
    double avg; // 평균을 저장할 변수 avg 선언

    // 배열 입력 및 합계 계산
    for (int i = 0; i < 5; i++) { // 배열의 크기만큼 반복 (0부터 4까지)
        scanf("%d", &num[i]); // 배열의 i번째 요소에 사용자 입력값 저장
        sum += num[i]; // 누적 합 (본래 주석 유지)
    }

    // 배열 크기 계산
    size = sizeof(num) / sizeof(num[0]); // 배열 전체 크기를 요소 크기로 나눠 요소 개수 계산

    // 평균 계산
    avg = sum / 5.0; // 평균 계산 (합계를 실수로 나눠 실수형 평균 값 도출)

    // 결과 출력
    printf("%.2lf", avg); // 평균값을 소수점 둘째 자리까지 출력

    return 0; // 프로그램 종료
}
