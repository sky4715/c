#include <stdio.h> // 표준 입출력 라이브러리를 포함한다.

int main(void) { // 메인 함수 시작
    int x, y, z, sum = 0; // 정수 x, y, z와 합계 sum을 선언하고 0으로 초기화한다.
    int result; // 입력 결과를 저장할 변수를 선언한다.

    printf("3개의 정수를 입력하시오(x, y, z): "); // 사용자에게 정수 입력을 요청한다.
    result = scanf("%d %d %d", &x, &y, &z); // 사용자로부터 정수를 입력받는다.

    // 입력이 성공적으로 이루어졌는지 확인한다.
    if (result != 3) { // 입력된 값의 개수가 3이 아닐 경우
        printf("잘못된 입력입니다. 정수를 입력하세요.\n"); // 잘못된 입력 메시지를 출력한다.
        return 1; // 오류 코드 1을 반환하며 프로그램을 종료한다.
    }

    sum = x + y + z; // 세 정수의 합계를 계산한다.
    printf("3개 정수의 합은 %d\n", sum); // 합계를 출력한다.
    return 0; // 프로그램이 정상적으로 종료됨을 나타낸다.
}
