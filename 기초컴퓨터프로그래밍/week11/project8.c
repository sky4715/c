#include <stdio.h> // 표준 입출력 라이브러리 포함
#define ROWS 3 // 배열의 행(학생 수)을 3으로 정의
#define COLS 5 // 배열의 열(각 학생의 점수 항목 수)을 5로 정의

int main(void){
    // 3x5 크기의 2차원 배열 a 초기화: 각 학생의 4개 점수와 1개의 감점 값
    int a[ROWS][COLS] = { { 87, 98, 80, 76, 3 }, { 99, 89, 90, 90, 0 }, { 65, 68, 50, 49, 0 }};
    
    int i; // 반복문에서 사용할 변수

    // 학생별로 점수를 계산하여 출력
    for (i = 0; i < ROWS; i++) { // i는 0부터 2까지 반복 (학생 수만큼 반복)
        // final_scores 계산: 각 학생의 4개 점수와 감점 값 계산
        double final_scores = a[i][0] * 0.3 + a[i][1] * 0.4 + a[i][2] * 0.2 + a[i][3] * 0.1 - a[i][4];
        
        // 각 학생의 최종 점수를 10자리 너비, 소수점 2자리로 출력
        printf("final score of student #%i=%10.2f\n", i + 1, final_scores); 
    }
    
    return 0; // 프로그램 종료
}
