#include <stdio.h>  // 표준 입출력 라이브러리 포함

int main(void) {
    int A[3][3] = {0};  // 3x3 배열 A 선언 및 초기화
    int B[3][3];        // 3x3 배열 B 선언 (초기화하지 않음)
    int n = 1;          // 숫자 증가용 변수 n을 1로 초기화

    // 배열 A에 값 자동 입력
    for (int i = 0; i < 3; i++) {           // 행 루프
        for (int k = 0; k < 3; k++)         // 열 루프
            A[i][k] = n++;                  // A[i][k]에 n을 대입하고 n 증가
    }

    printf("scalar_mult 전\n");             // 스칼라 곱 수행 전 메시지 출력

    // 배열 A 출력
    for (int y = 0; y < 3; y++) {           // 행 루프
        for (int x = 0; x < 3; x++) {       // 열 루프
            printf("%3d ", A[y][x]);        // A[y][x]의 값을 3칸 폭으로 출력
        }
        printf("\n");                       // 각 행의 출력 후 줄바꿈
    }

    // 식1) 계산 (스칼라 곱셈 수행: A * 2 -> B)
    for (int y = 0; y < 3; y++) {           // 행 루프
        for (int x = 0; x < 3; x++) {       // 열 루프
            B[y][x] = A[y][x] * 2;          // B[y][x]에 A[y][x] * 2의 값을 대입
        }
    }

    printf("scalar_mult 후\n");             // 스칼라 곱 수행 후 메시지 출력

    // 배열 B 출력
    for (int y = 0; y < 3; y++) {           // 행 루프
        for (int x = 0; x < 3; x++) {       // 열 루프
            printf("%3d ", B[y][x]);        // B[y][x]의 값을 3칸 폭으로 출력
        }
        printf("\n");                       // 각 행의 출력 후 줄바꿈
    }

    printf("\n===========\n\n");            // 구분선 출력

    // 배열 A에 값 자동 입력 (기존 값을 다시 초기화)
    n = 1;                                  // n을 1로 초기화
    for (int i = 0; i < 3; i++) {           // 행 루프
        for (int k = 0; k < 3; k++)         // 열 루프
            A[i][k] = n++;                  // A[i][k]에 n을 대입하고 n 증가
    }

    printf("transpose 전 \n");              // 전치 수행 전 메시지 출력

    // 배열 A 출력
    for (int y = 0; y < 3; y++) {           // 행 루프
        for (int x = 0; x < 3; x++) {       // 열 루프
            printf("%3d ", A[y][x]);        // A[y][x]의 값을 3칸 폭으로 출력
        }
        printf("\n");                       // 각 행의 출력 후 줄바꿈
    }

    // 식2) 계산 (전치 수행: A의 전치를 B에 저장)
    for (int y = 0; y < 3; y++) {           // 행 루프
        for (int x = 0; x < 3; x++) {       // 열 루프
            B[x][y] = A[y][x];              // B[x][y]에 A[y][x]의 값을 대입
        }
    }

    printf("transpose 후\n");               // 전치 수행 후 메시지 출력

    // 배열 B 출력 (전치 결과)
    for (int y = 0; y < 3; y++) {           // 행 루프
        for (int x = 0; x < 3; x++) {       // 열 루프
            printf("%3d ", B[y][x]);        // B[y][x]의 값을 3칸 폭으로 출력
        }
        printf("\n");                       // 각 행의 출력 후 줄바꿈
    }

    return 0;                               // 프로그램 종료
}
