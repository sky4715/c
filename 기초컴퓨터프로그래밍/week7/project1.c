#include <stdio.h>

int main(void){
    // while문: 조건을 먼저 평가하고 조건이 참일 때 반복문 실행
    int n = 0; // 초기값 설정

    while(n < 10){ // 조건식: n이 10보다 작을 때 반복
        printf("%d\t", n); // n 출력 (총 10회 반복)
        n++; // n을 1씩 증가
    }

    printf("\n"); // 줄바꿈

    // do-while문: 먼저 실행하고 나서 조건을 평가 (최소 1회 실행 보장)
    int k = 0; // 초기값 설정

    do{
        printf("%d\t", k); // k 출력 (최소 1회 실행)
        k++; // k를 1씩 증가
    }while(k < 10); // 조건식: k가 10보다 작을 때 반복

    printf("\n"); // 줄바꿈

    // for문: 초기값, 조건식, 증감식을 한 줄에 작성
    for(int a = 0; a < 10; a++){ // a를 0부터 9까지 반복
        printf("%d\t", a); // a 출력 (총 10회 반복)
    }

    return 0;
}
